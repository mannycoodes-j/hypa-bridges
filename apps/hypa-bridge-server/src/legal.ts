/**
 * Static legal / support pages served by the single-process host at
 * /support, /privacy, and /terms. Plain standalone HTML (no SPA dependency)
 * so they always resolve regardless of client-side routing.
 *
 * These are lightweight, honest documents for a stateless, no-account product.
 * Review the bracketed [placeholders] before publishing widely.
 */

type Section = { h: string; body: string };

const updated = "September 3, 2026";

function page(title: string, sections: Section[]): string {
  const body = sections
    .map(
      (s) => `
    <section>
      <h2>${s.h}</h2>
      ${s.body
        .split("\n")
        .map((p) => p.trim())
        .filter(Boolean)
        .map((p) => `<p>${p}</p>`)
        .join("\n      ")}
    </section>`,
    )
    .join("\n");

  return `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>${title} — Hypa Bridge</title>
    <style>
      :root { color-scheme: light dark; }
      * { box-sizing: border-box; }
      body {
        margin: 0;
        font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif;
        line-height: 1.6;
        color: #1a1a1a;
        background: #fafafa;
      }
      header { background: #111827; color: #f9fafb; padding: 2.5rem 1.25rem; }
      header .wrap { max-width: 760px; margin: 0 auto; }
      header h1 { margin: 0 0 .25rem; font-size: 1.5rem; }
      header p { margin: 0; opacity: .8; }
      main { max-width: 760px; margin: 0 auto; padding: 2rem 1.25rem 3rem; }
      h2 { font-size: 1.1rem; margin: 1.75rem 0 .5rem; }
      p { margin: .5rem 0; }
      a { color: #2563eb; }
      ul { margin: .5rem 0; padding-left: 1.25rem; }
      .muted { opacity: .7; font-size: .9rem; }
      footer { max-width: 760px; margin: 0 auto; padding: 1rem 1.25rem 3rem; }
      @media (prefers-color-scheme: dark) {
        body { color: #e5e7eb; background: #0b0f19; }
        header { background: #0b0f19; border-bottom: 1px solid #1f2937; }
        a { color: #60a5fa; }
      }
    </style>
  </head>
  <body>
    <header>
      <div class="wrap">
        <h1>Hypa Bridge — ${title}</h1>
        <p>Speak. Understand. Respond.</p>
      </div>
    </header>
    <main>
      <p class="muted">Last updated: ${updated}</p>${body}
    </main>
    <footer>
      <p class="muted">Questions? See the <a href="/support">support page</a>. Also read our
      <a href="/privacy">privacy policy</a> and <a href="/terms">terms of service</a>.</p>
    </footer>
  </body>
</html>`;
}

